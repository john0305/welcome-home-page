  const imgGrades = active.filter(l => l.current_image_grade !== undefined).map(l => l.current_image_grade!)
  const avgImgGrade = imgGrades.reduce((a, b) => a + b, 0) / imgGrades.length

  const dist = { a_plus: 0, a: 0, b: 0, c: 0, d: 0, f: 0 }
  for (const g of grades) {
    if (g >= 90) dist.a_plus++
    else if (g >= 80) dist.a++
    else if (g >= 70) dist.b++
    else if (g >= 60) dist.c++
    else if (g >= 50) dist.d++
    else dist.f++
  }

  // Fake 30-day views trend
  const now = Date.now()
  const viewsTrend = Array.from({ length: 30 }, (_, i) => ({
    date: new Date(now - (29 - i) * 86400000).toISOString().split('T')[0],
    value: Math.floor(80 + Math.random() * 120 + (i * 3)),
  }))
  const salesTrend = Array.from({ length: 30 }, (_, i) => ({
    date: new Date(now - (29 - i) * 86400000).toISOString().split('T')[0],
    value: Math.floor(0 + Math.random() * 4),
  }))

